"""
AICTE Sanyojika - Institutional Compliance & Audit Summary Dossier Exporter
Generates Markdown and structured JSON summaries ready for committee evaluation.
"""

import json
from typing import Dict, Any


def compile_dossier(
    institution_name: str,
    pid: str,
    compliance_score: float,
    active_grievance_count: int,
    overlap_count: int
) -> Dict[str, Any]:
    status = "EXEMPLARY" if compliance_score >= 80 else ("MONITORED" if compliance_score >= 50 else "CRITICAL")
    dossier = {
        "institution_name": institution_name,
        "pid": pid,
        "compliance_score": compliance_score,
        "standing": status,
        "active_grievances": active_grievance_count,
        "inter_bureau_overlaps": overlap_count,
        "requires_joint_inspection": overlap_count > 0 or compliance_score < 50
    }
    return dossier


def format_markdown_dossier(dossier: Dict[str, Any]) -> str:
    md = f"""# AICTE SANYOJIKA - INSTITUTIONAL AUDIT DOSSIER
**Institution:** {dossier['institution_name']} (PID: {dossier['pid']})
**Compliance Index:** {dossier['compliance_score']}/100.0 [{dossier['standing']}]
**Active Grievances:** {dossier['active_grievances']}
**Cross-Bureau Overlaps:** {dossier['inter_bureau_overlaps']}
**Joint Inspection Mandated:** {'YES (High Priority)' if dossier['requires_joint_inspection'] else 'NO (Normal Standing)'}
---
*Generated by AICTE Sanyojika Intelligence Engine v2.5*
"""
    return md


if __name__ == "__main__":
    sample = compile_dossier("Delhi Institute of Technology", "1-1049281", 44.5, 12, 3)
    print(format_markdown_dossier(sample))
